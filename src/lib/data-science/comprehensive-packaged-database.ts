export function lookupComprehensivePackagedProduct(query: string): PackagedProduct | undefined {
  const clean = query.trim().toLowerCase();
  return COMPREHENSIVE_PACKAGED_DATABASE.find(
    (p) => p.barcode === clean || p.productName.toLowerCase().includes(clean) || p.brand.toLowerCase().includes(clean)
  );
}

export function decodeGS1Prefix(barcode: string) {
  const clean = barcode.trim();
  if (clean.length >= 7) {
    const prefix7 = clean.slice(0, 7);
    if (GS1_MANUFACTURER_MAP[prefix7]) {
      return GS1_MANUFACTURER_MAP[prefix7];
    }
  }
  if (clean.startsWith("890")) {
    return {
      brand: "Indian Registered FMCG Brand",
      company: "GS1 India Registered Enterprise (Prefix 890)",
      category: "Indian Packaged Food Item",
      defaultNova: 3
    };
  }
  return null;
}
